def render_markdown(doc: dict[str, Any]) -> str:
    lines = [f"# {doc['title']}"]
    if doc.get("subtitle"):
        lines.append(f"_{doc['subtitle']}_")
    meta = []
    if doc.get("author"):
        meta.append(f"**Author:** {doc['author']}")
    if doc.get("generated_at"):
        meta.append(f"**Generated:** {doc['generated_at']}")
    if meta:
        lines.append("  \n".join(meta))
    if doc.get("synthesis") == "deterministic":
        lines.append("")
        lines.append("> **Note:** composed deterministically from the brief because no language model was available. No external facts were added.")
    lines.append("")
    for section in doc.get("sections", []):
        lines.append(f"## {section.get('heading', '')}")
        lines.append("")
        if section.get("body"):
            lines.append(str(section["body"]))
            lines.append("")
        for bullet in section.get("bullets") or []:
            lines.append(f"- {bullet}")
        if section.get("bullets"):
            lines.append("")
    lines.append("---")
    lines.append("_Generated by LocalAI Workspace_")
    return "\n".join(lines)


def _to_text(doc: dict[str, Any]) -> str:
    md = render_markdown(doc)
    md = re.sub(r"^#+\s*", "", md, flags=re.M)
    return md.replace("**", "").replace("_", "")


def _to_docx(doc: dict[str, Any]) -> bytes:
    from docx import Document
    from docx.shared import Pt

    document = Document()
    document.add_heading(doc["title"], level=0)
    if doc.get("subtitle"):
        p = document.add_paragraph(doc["subtitle"])
        p.runs[0].italic = True
    if doc.get("author") or doc.get("generated_at"):
        info = document.add_paragraph()
        run = info.add_run(f"Author: {doc.get('author', '-')} | Generated: {doc.get('generated_at', '')}")
        run.font.size = Pt(9)
    for section in doc.get("sections", []):
        document.add_heading(section.get("heading", ""), level=1)
        if section.get("body"):
            document.add_paragraph(str(section["body"]))
        for bullet in section.get("bullets") or []:
            document.add_paragraph(str(bullet), style="List Bullet")
    document.add_paragraph("Generated by LocalAI Workspace")
    buf = io.BytesIO()
    document.save(buf)
    return buf.getvalue()


def _to_pdf(doc: dict[str, Any]) -> bytes:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import cm
    from reportlab.platypus import ListFlowable, ListItem, Paragraph, SimpleDocTemplate, Spacer

    buf = io.BytesIO()
    styles = getSampleStyleSheet()
    story: list[Any] = [Paragraph(_esc(doc["title"]), styles["Title"]), Spacer(1, 0.4 * cm)]
    if doc.get("subtitle"):
        story.append(Paragraph(_esc(doc["subtitle"]), styles["Italic"]))
    story.append(Paragraph(f"Generated by LocalAI Workspace — {_esc(doc.get('generated_at', ''))}", styles["Normal"]))
    story.append(Spacer(1, 0.6 * cm))
    for section in doc.get("sections", []):
        story.append(Paragraph(_esc(section.get("heading", "")), styles["Heading2"]))
        if section.get("body"):
            story.append(Paragraph(_esc(section["body"]), styles["BodyText"]))
        bullets = section.get("bullets") or []
        if bullets:
            story.append(
                ListFlowable([ListItem(Paragraph(_esc(b), styles["BodyText"])) for b in bullets], bulletType="bullet", start="•")
            )
        story.append(Spacer(1, 0.3 * cm))
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm, topMargin=2 * cm, bottomMargin=2 * cm).build(story)
    return buf.getvalue()


def _esc(text: Any) -> str:
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def _chat_usable(registry: Any) -> bool:
    if registry is None:
        return False
    checker = getattr(registry, "chat_available", None)
    if callable(checker):
        try:
            return bool(checker())
        except Exception:  # noqa: BLE001
            return False
    try:
        return bool(registry.chat_models())
    except Exception:  # noqa: BLE001
        return False


